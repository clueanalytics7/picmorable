import JSZip from 'jszip';
import { AlbumMetadata, AlbumPhoto, AlbumPage } from '../types/album';

/**
 * Downloads a single text file or blob directly from the browser without server roundtrip.
 */
export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/**
 * Creates and downloads a human-readable Archival Transcript of the entire album.
 */
export function generateAlbumTranscript(
  meta: AlbumMetadata,
  photos: AlbumPhoto[],
  pages: AlbumPage[]
): string {
  const photoMap = new Map(photos.map(p => [p.id, p]));
  const separator = '='.repeat(68);
  const thinSeparator = '-'.repeat(68);

  let text = `${separator}\n`;
  text += `PICMORABLE — TRADITIONAL HARDCOVER PHOTO ALBUM ARCHIVE\n`;
  text += `Privacy-First Client-Side Preservation Record\n`;
  text += `${separator}\n\n`;

  text += `ALBUM TITLE:       ${meta.title.toUpperCase()}\n`;
  if (meta.subtitle) {
    text += `SUBTITLE:          ${meta.subtitle}\n`;
  }
  text += `CURATOR / FAMILY:  ${meta.curator || 'Private Archive'}\n`;
  text += `DATE / PERIOD:     ${meta.dateRange || 'Undated'}\n`;
  text += `COVER BINDING:     ${meta.coverMaterial} with ${meta.foilStyle} foil stamping\n`;
  text += `CORNER MOUNTING:   ${meta.cornerStyle}\n`;
  text += `CREATED:           ${new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })}\n\n`;

  text += `${thinSeparator}\n`;
  text += `ALBUM OVERVIEW & NARRATIVE STORY:\n`;
  text += `${thinSeparator}\n`;
  text += `${meta.description || 'No album narrative provided.'}\n\n`;

  text += `${separator}\n`;
  text += `REARRANGED PLATES & PHOTO CAPTIONS (${photos.length} PHOTOGRAPHS ACROSS ${pages.length} PAGES)\n`;
  text += `${separator}\n\n`;

  pages.forEach((page) => {
    text += `[ PAGE ${page.pageNumber} — ${page.customTitle || 'Memory Plate'} (Template: ${page.templateId}) ]\n`;
    if (page.photoIds.length === 0) {
      text += `  (No photographs placed on this page)\n\n`;
      return;
    }

    page.photoIds.forEach((photoId, slotIdx) => {
      const photo = photoMap.get(photoId);
      if (!photo) return;

      text += `  Item #${slotIdx + 1}: ${photo.name}\n`;
      if (photo.date) text += `    Date Taken:   ${photo.date}\n`;
      if (photo.location) text += `    Location:     ${photo.location}\n`;
      text += `    Description:  "${photo.caption || 'No caption written.'}"\n`;
    });
    text += `\n`;
  });

  text += `${separator}\n`;
  text += `PRESERVATION GUARANTEE:\n`;
  text += `All images and captions were organized on-device with zero telemetry\n`;
  text += `or remote uploads. Generated by Picmorable.\n`;
  text += `${separator}\n`;

  return text;
}

/**
 * Packages the entire album into a ZIP containing:
 * 1. All rearranged photos organized by page and item index.
 * 2. album_manifest.json (full structured data).
 * 3. ALBUM_STORY_AND_CAPTIONS.txt (readable transcript).
 */
export async function exportAlbumPackageZip(
  meta: AlbumMetadata,
  photos: AlbumPhoto[],
  pages: AlbumPage[],
  onProgress?: (progress: number, status: string) => void
): Promise<void> {
  const zip = new JSZip();
  const photoMap = new Map(photos.map(p => [p.id, p]));

  onProgress?.(5, 'Preparing archival manifest and transcript...');

  // 1. Archival Transcript
  const transcript = generateAlbumTranscript(meta, photos, pages);
  zip.file('ALBUM_STORY_AND_CAPTIONS.txt', transcript);

  // 2. Structured Manifest JSON
  const manifest = {
    version: '1.0',
    exportedAt: new Date().toISOString(),
    privacyNotice: '100% processed locally on-device. Zero images uploaded to external servers.',
    metadata: meta,
    pages: pages.map(page => ({
      pageNumber: page.pageNumber,
      templateId: page.templateId,
      customTitle: page.customTitle,
      photos: page.photoIds.map(id => {
        const photo = photoMap.get(id);
        return {
          id: photo?.id,
          originalFilename: photo?.name,
          caption: photo?.caption,
          date: photo?.date,
          location: photo?.location,
          aspectRatio: photo?.aspectRatio,
        };
      }),
    })),
  };
  zip.file('album_manifest.json', JSON.stringify(manifest, null, 2));

  // 3. Photos folder
  const photosFolder = zip.folder('photos');
  let loadedCount = 0;
  const totalPhotos = photos.length;

  for (let pageIdx = 0; pageIdx < pages.length; pageIdx++) {
    const page = pages[pageIdx];
    for (let slotIdx = 0; slotIdx < page.photoIds.length; slotIdx++) {
      const photoId = page.photoIds[slotIdx];
      const photo = photoMap.get(photoId);
      if (!photo) continue;

      const pageNumPad = String(page.pageNumber).padStart(2, '0');
      const itemNumPad = String(slotIdx + 1).padStart(2, '0');
      const cleanName = photo.name.replace(/[^a-zA-Z0-9._-]/g, '_');
      const targetFilename = `page_${pageNumPad}_item_${itemNumPad}_${cleanName}`;

      try {
        if (photo.blob) {
          photosFolder?.file(targetFilename, photo.blob);
        } else {
          // Fetch from objectUrl or remote sample asset
          const res = await fetch(photo.url);
          const blob = await res.blob();
          photosFolder?.file(targetFilename, blob);
        }
      } catch (err) {
        console.warn(`Could not bundle image ${photo.name}`, err);
      }

      loadedCount++;
      const pct = Math.round(10 + (loadedCount / Math.max(1, totalPhotos)) * 75);
      onProgress?.(pct, `Packaging photograph ${loadedCount} of ${totalPhotos}...`);
    }
  }

  onProgress?.(90, 'Compressing archive in browser memory...');
  const zipBlob = await zip.generateAsync({ type: 'blob' });

  onProgress?.(100, 'Download ready!');
  const sanitizedAlbumTitle = meta.title.toLowerCase().replace(/[^a-z0-9]/g, '_').slice(0, 30);
  downloadBlob(zipBlob, `picmorable_${sanitizedAlbumTitle}_archive.zip`);
}

/**
 * Draws a high-resolution canvas snapshot of an album page spread and downloads as PNG.
 */
export async function exportSpreadAsCanvas(
  spreadEl: HTMLElement,
  spreadName: string = 'album_spread'
): Promise<void> {
  const rect = spreadEl.getBoundingClientRect();
  const scale = 2; // High-res 2x retina render
  const canvas = document.createElement('canvas');
  canvas.width = rect.width * scale;
  canvas.height = rect.height * scale;
  const ctx = canvas.getContext('2d');
  if (!ctx) return;

  ctx.scale(scale, scale);

  // Background parchment fill
  ctx.fillStyle = '#1c1917'; // Dark presentation mat
  ctx.fillRect(0, 0, rect.width, rect.height);

  // Use SVG foreignObject trick or basic rasterizer
  const data = `
    <svg xmlns="http://www.w3.org/2000/svg" width="${rect.width}" height="${rect.height}">
      <foreignObject width="100%" height="100%">
        <div xmlns="http://www.w3.org/1999/xhtml">
          ${spreadEl.outerHTML}
        </div>
      </foreignObject>
    </svg>
  `;

  const img = new Image();
  const svgBlob = new Blob([data], { type: 'image/svg+xml;charset=utf-8' });
  const url = URL.createObjectURL(svgBlob);

  await new Promise<void>((resolve) => {
    img.onload = () => {
      ctx.drawImage(img, 0, 0);
      URL.revokeObjectURL(url);
      resolve();
    };
    img.onerror = () => {
      URL.revokeObjectURL(url);
      resolve();
    };
    img.src = url;
  });

  canvas.toBlob((blob) => {
    if (blob) {
      downloadBlob(blob, `${spreadName}.png`);
    }
  }, 'image/png');
}
